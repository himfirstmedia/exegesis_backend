export const normalizeBookLanguage = (language) =>
  String(language || "en")
    .toLowerCase()
    .split(/[-_]/)[0];

export const getBookNameMap = (language) =>
  BIBLE_BOOK_NAMES[normalizeBookLanguage(language)] || BIBLE_BOOK_NAMES.en;

export const localizeBookName = (bookName, language) => {
  if (!bookName) return "";
  const canonical = BOOK_NAME_ALIASES[bookName] || bookName;
  return getBookNameMap(language)[canonical] || canonical;
};

const ALL_REFERENCE_NAMES = [
  ...new Set([
    ...Object.keys(BIBLE_BOOK_NAMES.en),
    ...Object.keys(BOOK_NAME_ALIASES),
  ]),
].sort((a, b) => b.length - a.length);

const escapeRegExp = (value) =>
  value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/**
 * Replace every English book name that is immediately followed by a chapter
 * number with its localized form. Matching all occurrences (not just the first
 * one) handles references such as "Romans 8:28; Ephesians 2:8". The chapter
 * lookahead keeps ordinary prose that happens to contain a book name intact.
 */
export const localizeReferenceText = (value, language) => {
  if (typeof value !== "string") return value;
  const map = getBookNameMap(language);
  let text = value.trim();
  if (!text) return value;
  for (const name of ALL_REFERENCE_NAMES) {
    const canonical = BOOK_NAME_ALIASES[name] || name;
    const localized = map[canonical] || canonical;
    if (localized === name) continue;
    const pattern = new RegExp(
      `(^|[^A-Za-z])${escapeRegExp(name)}(?=\\s+\\d)`,
      "gi",
    );
    text = text.replace(pattern, (match, prefix) => `${prefix}${localized}`);
  }
  return text;
};

export const buildLocalizedReference = (record, language) => {
  if (!record) return "";
  if (record.bookName) {
    const book = localizeBookName(record.bookName, language);
    const chapter = record.chapter;
    const verse = record.verseNumber ?? record.verse;
    if (chapter !== undefined && chapter !== null) {
      const suffix = verse !== undefined && verse !== null ? `:${verse}` : "";
      return `${book} ${chapter}${suffix}`;
    }
    return book;
  }
  const source = record.passageReference || record.reference;
  return source ? localizeReferenceText(String(source), language) : "";
};

export const splitCrossReference = (value) => {
  if (typeof value !== "string") return null;
  const match = value.match(/^(.+?)(\s+[—–-]\s+|\s*—\s*)(.+)$/);
  if (!match) return null;
  return { reference: match[1].trim(), separator: match[2], text: match[3].trim() };
};
